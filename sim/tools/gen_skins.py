"""Turn design/skins/packs (skins.json + PNG layers + thumbnails) into skins_gen.c.

Backgrounds are RLE-compressed RGB565 (lossless): runs of identical pixels are stored once,
which suits the mostly-black art. Thumbnails are raw RGB565. Pure stdlib (no Pillow).

    python3 sim/tools/gen_skins.py <packs dir> <out .c> [swap]
'swap' writes RGB565 big-endian (for LV_COLOR_16_SWAP=y on the device).
"""
import json
import os
import struct
import sys
import zlib


def png_rgb(path):
    data = open(path, "rb").read()
    pos, idat, w, h, bpp = 8, b"", 0, 0, 3
    while pos < len(data):
        n, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + n]
        if typ == b"IHDR":
            w, h, depth, ctype = struct.unpack(">IIBB", body[:10])
            assert depth == 8 and ctype in (2, 6), f"{path}: need 8-bit RGB/RGBA"
            bpp = 3 if ctype == 2 else 4
        elif typ == b"IDAT":
            idat += body
        pos += 12 + n
    raw, stride = zlib.decompress(idat), w * bpp
    rows, prev, i = [], bytearray(stride), 0
    for _ in range(h):
        ft, line = raw[i], bytearray(raw[i + 1:i + 1 + stride]); i += 1 + stride
        for x in range(stride):
            a = line[x - bpp] if x >= bpp else 0
            b, c = prev[x], (prev[x - bpp] if x >= bpp else 0)
            if ft == 1: line[x] = (line[x] + a) & 255
            elif ft == 2: line[x] = (line[x] + b) & 255
            elif ft == 3: line[x] = (line[x] + (a + b) // 2) & 255
            elif ft == 4:
                p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line); prev = line
    px = []
    for row in rows:
        for x in range(0, w * bpp, bpp):
            r, g, b = row[x], row[x + 1], row[x + 2]
            px.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    return w, h, px


def le(v, swap):
    return bytes((v >> 8, v & 255)) if swap else bytes((v & 255, v >> 8))


def rle(px, swap):
    """token n<128: n+1 literal pixels follow; n>=128: next pixel repeated n-126 times (2..129)"""
    out, i, N = bytearray(), 0, len(px)
    while i < N:
        j = i
        while j + 1 < N and px[j + 1] == px[i] and j - i < 128:
            j += 1
        run = j - i + 1
        if run >= 2:
            out.append(128 + run - 2)
            out += le(px[i], swap)
            i = j + 1
            continue
        k = i
        while k < N and k - i < 128 and not (k + 1 < N and px[k + 1] == px[k]):
            k += 1
        k = max(k, i + 1)
        out.append(k - i - 1)
        for v in px[i:k]:
            out += le(v, swap)
        i = k
    return bytes(out)


KIND = dict(
    frame=dict(notched=0, brackets=1, double=2, ticks=3, dashed=4),
    meter=dict(vseg=0, dots=1, twin=2, hseg=3, arc=4),
    lamps=dict(grid=0, switcher=1, domes=2, pills=3, diamonds=4, matrix=5),
    rotor=dict(scomp=0, reticle=1, square=2, twin=3, radar=4, gear=5),
    keys=dict(bevel=0, flat=1, strip=2, ring=3, pill=4),
)
PART = dict(scope=0, round=1, vscope=2, target=3, waterfall=4, meter=5, batt=6, lamps=7, edge=8,
            readout=9, rotor=10, bars=11, ring=12, gauge=13, hex=14, temp=15)
STYLE = dict(scope="frame", vscope="frame", meter="meter", lamps="lamps", rotor="rotor")
MAX_PARTS = 12


def part_c(pt):
    """["kind", style, flags, g...] -> C initializer; style may be a name (frame/meter/...)"""
    kind, style, flags, g = pt[0], pt[1], pt[2], list(pt[3:])
    if isinstance(style, str):
        style = {"v": 0, "h": 1}[style] if kind == "batt" else KIND[STYLE[kind]][style]
    g = [int(round(v)) for v in (g + [0] * 6)[:6]]
    return "{ %d, %d, %d, { %s } }" % (PART[kind], style, flags, ", ".join(map(str, g)))


def hx(c):
    return "0x" + c.lstrip("#").upper()


def carr(f, name, data):
    f.write(f"static const uint8_t {name}[{len(data)}] = {{")
    f.write(",".join(map(str, data)))
    f.write("};\n")


def main():
    packs, out = sys.argv[1], sys.argv[2]
    swap = len(sys.argv) > 3 and sys.argv[3] == "swap"
    skins = json.load(open(os.path.join(packs, "skins.json")))
    total = 0
    with open(out, "w") as f:
        f.write("/* generated by sim/tools/gen_skins.py - do not edit */\n#include \"skin.h\"\n")
        for s in skins:
            i = s["id"]
            w, h, px = png_rgb(os.path.join(packs, "%02d_thumb.png" % i))
            carr(f, f"thumb_{i}", b"".join(le(v, swap) for v in px))
            if i > 0:
                for layer in ("main", "lock"):
                    w, h, px = png_rgb(os.path.join(packs, "%02d_%s.png" % (i, layer)))
                    assert (w, h) == (368, 448)
                    data = rle(px, swap)
                    total += len(data)
                    carr(f, f"bg_{layer}_{i}", data)
        f.write("const skin_desc_t SKIN_TABLE[] = {\n")
        for s in skins:
            i, p, parts = s["id"], s["palette"], s["parts"]
            assert len(parts) <= MAX_PARTS, s["name"]
            assert sum(1 for pt in parts if pt[2] & 1) == 1, s["name"] + ": exactly one part holds the temp"
            bg = (f"bg_main_{i}, bg_lock_{i}, sizeof(bg_main_{i}), sizeof(bg_lock_{i})" if i > 0
                  else "0, 0, 0, 0")
            plist = ",\n        ".join(part_c(pt) for pt in parts)
            f.write(f"""    {{ "{s['name']}",
      {hx(p['frame'])}, {hx(p['grid'])}, {hx(p['trace'])}, {hx(p['accent'])}, {hx(p['text'])}, {hx(p['tick'])}, {hx(p['key'])}, {hx(p['hex'])},
      {{ {', '.join(hx(c) for c in p['lamps'])} }},
      {KIND['keys'][s['keys']]}, {len(parts)},
      {{ {plist} }},
      {bg}, thumb_{i} }},
""")
        f.write("};\nconst int SKIN_COUNT = %d;\n" % len(skins))
    print(f"skins_gen.c: {len(skins)} skins, backgrounds {total // 1024} KB RLE")


if __name__ == "__main__":
    main()
